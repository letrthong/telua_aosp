import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


class TestSphinxPlantUML(unittest.TestCase):
    def test_sphinx_plantuml_build(self):
        wrapper = Path(__file__).resolve().parent.parent / "sphinx" / "scripts" / "plantuml_wrapper.py"
        self.assertTrue(wrapper.is_file(), f"plantuml_wrapper.py not found at {wrapper}")

        with tempfile.TemporaryDirectory() as td:
            src = Path(td) / "src"
            out = Path(td) / "out"
            src.mkdir()

            conf = f"""
import sys
project = 'PlantUML Test'
extensions = ['sphinxcontrib.plantuml']
plantuml = [sys.executable, r'{wrapper}']
plantuml_output_format = 'svg_img'
"""
            (src / "conf.py").write_text(conf, encoding="utf-8")

            rst = """Test PlantUML
==============

.. uml::

   @startuml
   actor User
   participant "Frontend" as UI
   participant "Backend" as API
   database "Database" as DB

   User -> UI : Action
   UI -> API : Request
   API -> DB : Query
   DB --> API : Data
   API --> UI : Response
   UI --> User : Render
   @enduml
"""
            (src / "index.rst").write_text(rst, encoding="utf-8")

            res = subprocess.run(
                [sys.executable, "-m", "sphinx", "-b", "html", str(src), str(out)],
                capture_output=True,
                text=True,
                timeout=30,
            )
            self.assertEqual(res.returncode, 0, f"Sphinx build failed: {res.stderr}\n{res.stdout}")

            svg_images = list((out / "_images").glob("*.svg"))
            self.assertGreater(len(svg_images), 0, "No SVG image generated by PlantUML")
            svg_content = svg_images[0].read_text(encoding="utf-8")
            self.assertTrue("<svg" in svg_content, "Generated file is not valid SVG")
            html = (out / "index.html").read_text(encoding="utf-8")
            print("\n[SPHINX GENERATED HTML FOR PLANTUML]:")
            for line in html.splitlines():
                if "plantuml" in line.lower() or "img" in line.lower():
                    print(line)


if __name__ == "__main__":
    unittest.main()
